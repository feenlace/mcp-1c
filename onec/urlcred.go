package onec

import (
	"errors"
	"fmt"
	"net/url"
	"strings"
)

// urlcred.go отделяет учётные данные от базового адреса 1С там, где адрес
// входит в процесс, чтобы ни одно поле, которое кто-то может прочитать или
// напечатать, никогда не хранило пароль.
//
// ПОЧЕМУ НА ГРАНИЦЕ, А НЕ В МЕСТЕ ПЕЧАТИ. Флаг --base принимает адрес, а
// --user и --password принимают учётные данные, но раздельность никогда не
// проверялась: cmd/mcp-1c/main.go кладёт значение флага в cfg.BaseURL как есть
// и передаёт его в onec.NewClient как BaseURL. Дальше строка склеивается с
// именем метода в onec/client.go, в Get и в Post, и попадает в
// *url.Error, чей Error() печатает %q сырого адреса
// (/usr/local/go/src/net/url/url.go:40). Отредактировать одно место печати
// недостаточно: пароль остался бы в структуре, и следующий читатель
// Client.BaseURL потёк бы снова.
//
// ЭТО НЕ МЁРТВЫЙ ПАРАМЕТР. Измерено на локальном слушателе: если в адресе
// есть userinfo и нет --user, net/http сам превращает userinfo в реальный
// заголовок Basic (/usr/local/go/src/net/http/client.go:251), то есть
// администраторы, записавшие учётные данные в адрес, действительно
// аутентифицировались ими. Поэтому учётные данные ПЕРЕНОСЯТСЯ в поля клиента,
// а не выбрасываются.
//
// ПОЛИТИКА: РАЗБОР ПО RFC 3986 СРЕДСТВАМИ net/url, ОТКАЗ ПРИ ЛЮБОЙ
// НЕОДНОЗНАЧНОСТИ. Ручной побайтовой хирургии здесь нет намеренно. Разбор
// «по символам» уже дал утечку: для адреса http://admin:p@ss/w0rd@host/hs
// RFC 3986 говорит, что authority кончается на первом «/», а userinfo это всё
// до ПОСЛЕДНЕГО «@» внутри authority, то есть логин admin, пароль p, хост ss,
// а хвост w0rd@host остаётся в пути. Разбор верный, замысел администратора
// другой, и выразить его без процентного кодирования нельзя. Поэтому здесь не
// угадывают замысел, а отказывают и объясняют, что делать.

// ErrURLCredentialUnstrippable возвращается для адреса с учётными данными,
// который принять нельзя. Сообщение не содержит ни одного байта самого адреса.
//
// ПОЧЕМУ ПРИЧИНА НАЗВАНА ДВУМЯ ВАРИАНТАМИ. Сюда приходят две разные беды, и
// сказать про обе только первую было бы неправдой. Шаги 1..4 и 6 попадают сюда
// потому, что отделить учётные данные однозначно НЕЛЬЗЯ. Шаг 5 попадает сюда
// потому, что в адресе есть «?» или «#», и учётные данные при этом отделяются
// прекрасно: их печатают первыми, потому что пароль в адресе срочнее строки
// запроса.
//
// ПОЧЕМУ ПРО «?» И «#» СКАЗАНО ДО СОВЕТА ПРО КОДИРОВАНИЕ. Совет «уберите логин
// и пароль» для адреса шага 5 доводит читателя ровно до половины: измерено, что
// http://Admin:secret@localhost:8080/hs/mcp-1c?debug=1 после переноса учётных
// данных во флаги превращается в адрес, который отклоняется ЗАНОВО, уже
// ErrBaseURLHasQueryOrFragment. Читатель видит только это сообщение и только
// один раз, поэтому обе помехи названы в нём сразу.
//
// ПОЧЕМУ «ВНУТРИ НИХ». Процентное кодирование здесь относится к служебным
// символам ЛОГИНА И ПАРОЛЯ, а не к строке запроса: %3F и %23 в пароле проверены
// испытанием и работают, а превращать настоящий «?» в %3F значит вписать строку
// запроса в путь, то есть получить другой адрес, а не исправленный.
var ErrURLCredentialUnstrippable = errors.New(
	"адрес 1С отклонён: в нём записаны логин и пароль, и либо отделить их от адреса однозначно невозможно, " +
		"либо в адресе есть ещё и ? или #. " +
		"Уберите логин и пароль из адреса и задайте их флагами --user и --password, " +
		"а в самом адресе оставьте только корень HTTP-сервиса, без ? и #: адрес со строкой запроса или якорем " +
		"отклоняется отдельной проверкой, даже когда логина и пароля в нём уже нет. " +
		"Если логин и пароль обязаны остаться в адресе, закодируйте служебные символы внутри них: " +
		"@ как %40, / как %2F, ? как %3F, # как %23")

// ErrBaseURLAmbiguousAt возвращается для адреса, в пути которого стоит «@», а
// перед ней есть двоеточие. Такой адрес читается двумя способами сразу, и
// выбрать между ними нельзя.
//
// ЗАЧЕМ ОТДЕЛЬНОЕ СООБЩЕНИЕ. Здесь net/url НЕ НАШЁЛ никаких учётных данных
// (parsed.User == nil), поэтому фраза «адрес содержит логин и пароль» была бы
// неправдой, а совет «уберите логин и пароль» ничего не описывал бы: убирать
// нечего. Отказ всё равно нужен, потому что двоеточие перед «@» это ровно то,
// чем отличается http://user:1234/passZ@host/hs, где 1234/passZ это половина
// пароля, от http://сервер/hs/mcp-1c@v2, где «@» это просто символ пути.
//
// ГДЕ ИМЕННО ЭТО ДВОЕТОЧИЕ. Условие шага 4 читает его в ДВУХ местах, и сообщение
// обязано назвать оба, иначе половина читателей ищет символ, которого у них нет.
// Измерено: у http://localhost:8080/base/hs/mcp-1c@v2 сработала ветка
// parsed.Port() != "", то есть двоеточие ПЕРЕД НОМЕРОМ ПОРТА, а в пути
// /base/hs/mcp-1c@v2 двоеточия нет вовсе; тот же адрес без порта принимается. У
// http://us/er:passZZ@host/hs, наоборот, порта нет, и двоеточие стоит в самом
// пути. Прежний текст называл только путь и уводил читателя первого случая не
// туда.
//
// Совет про %40 здесь ПРОВЕРЕН испытанием: адрес, в котором «@» записана как
// %40, этой проверкой не отклоняется, потому что проверяется сырой путь.
var ErrBaseURLAmbiguousAt = errors.New(
	"адрес 1С читается двояко и поэтому отклонён: в нём есть знак @ после имени сервера, " +
		"а перед ним стоит двоеточие, и это либо двоеточие перед номером порта, либо двоеточие в самом пути. " +
		"Поэтому всё, что стоит до @, читается и как часть адреса, и как логин с паролем. " +
		"Если это логин и пароль, уберите их из адреса и задайте флагами --user и --password. " +
		"Если @ это часть пути или имени сервиса, запишите её как %40")

// ErrBaseURLHasQueryOrFragment возвращается для адреса с «?» или «#».
// Такой адрес нерабочий: onec/client.go в Get и в Post склеивает BaseURL с именем
// метода, а имя метода всегда начинается с «/», поэтому оно попадёт внутрь
// строки запроса. Всё, что стоит после «?», при этом осталось бы в адресе,
// который видит модель.
var ErrBaseURLHasQueryOrFragment = errors.New(
	"адрес 1С содержит ? или #, поэтому он отклонён. К адресу дописывается имя метода HTTP-сервиса, " +
		"поэтому всё, что стоит после ? или #, ломает запрос и остаётся в адресе, который видит модель. " +
		"Укажите корневой адрес HTTP-сервиса, например http://сервер/база/hs/mcp-1c")

// ErrBaseURLUnparsable возвращается для адреса, который net/url не разбирает и
// в котором нет «@», то есть речь не про учётные данные. Оборачивать исходную
// ошибку нельзя: *url.Error печатает %q сырого адреса.
//
// ЧТО НА САМОМ ДЕЛЕ СЮДА ДОХОДИТ. Шаг 1 возвращает байт в байт любой адрес без
// «@», «?» и «#» и НЕ РАЗБИРАЕТ его вовсе, поэтому до url.Parse доживает только
// адрес, в котором есть «?» или «#». Отсюда два следствия для текста.
//
// Первое: прежний совет «проверьте, что адрес записан без пробелов» называл
// причину, которая это сообщение произвести не может. Измерено:
// http://localhost:80 80/hs/mcp-1c url.Parse не разбирает («invalid port»), но
// шаг 1 отдаёт его как есть, и он ПРИНИМАЕТСЯ; тот же адрес с «?x=1» на конце
// доходит до разбора и получает этот отказ. Пробел был не причиной, а спутником.
//
// Второе: советовать здесь --user и --password нельзя, и это структурно, а не
// по вкусу: ветка выше забирает себе КАЖДЫЙ адрес с «@», поэтому в адресе,
// дошедшем сюда, учётных данных не бывает и переносить во флаги нечего.
var ErrBaseURLUnparsable = errors.New(
	"адрес 1С отклонён: в нём есть ? или #, и разобрать его как адрес не получается. " +
		"Укажите корневой адрес HTTP-сервиса, без строки запроса и без якоря, " +
		"например http://сервер/база/hs/mcp-1c")

// BaseURLSplit — результат разбора базового адреса.
//
// При отказе возвращается НУЛЕВОЙ BaseURLSplit: в нём нет ни одного байта
// исходного адреса, поэтому его безопасно положить в любое поле и напечатать.
type BaseURLSplit struct {
	// Base — адрес без учётных данных. Для адреса без учётных данных это
	// исходная строка байт в байт.
	Base string
	// User и Password — учётные данные, снятые с адреса, уже раскодированные
	// (процентные последовательности разрешены) ровно так, как их разрешает
	// net/url, потому что именно в таком виде net/http положил бы их в
	// заголовок Authorization.
	User     string
	Password string
	// HadUserinfo сообщает, что в адресе были учётные данные и они сняты.
	// Именно это, а не «User != \"\"», решает, отправлять ли Basic: адрес
	// http://:pw@host сегодня даёт заголовок Basic OnB3 с пустым логином.
	HadUserinfo bool
	// Display — «схема://хост» для показа человеку и модели. Собирается
	// ТОЛЬКО из Scheme и Host разобранного адреса, поэтому не может содержать
	// ни userinfo (net/url кладёт её в отдельное поле User), ни строку
	// запроса, ни путь. Для отклонённого адреса пустая строка.
	Display string
}

// SplitURLCredentials разбирает базовый адрес 1С по RFC 3986 средствами
// net/url и отделяет от него учётные данные.
//
// Что принимается:
//   - адрес без «@», «?» и «#» — возвращается байт в байт, без учётных данных;
//     это то, что оставляет нетронутыми внутренние адреса вида proxy://Имя,
//     poll://local и пустую строку;
//   - адрес с ОДНИМ userinfo в authority и без «@» в пути — учётные данные
//     снимаются, остальное собирается обратно через net/url;
//     сюда попадает http://admin:p@ssw0rd@host/hs, потому что net/url
//     разрешает «@» внутри userinfo (url.go:1282-1292) и берёт последнюю «@».
//
// Что отклоняется:
//   - адрес, который net/url не разбирает (сырая кириллица в userinfo,
//     битая процентная последовательность, «/» «?» «#» в пароле);
//   - адрес без authority (opaque): «http:user:pass@host», «user:pass@host:8080»;
//   - адрес с «?» или «#» (см. ErrBaseURLHasQueryOrFragment);
//   - адрес с userinfo, у которого в пути есть ещё одна незакодированная «@»;
//   - адрес, в пути которого есть незакодированная «@», а перед ней двоеточие
//     (см. ErrBaseURLAmbiguousAt);
//   - адрес, у которого после снятия userinfo повторный разбор даёт другой
//     хост или снова находит userinfo.
//
// Незакодированная «@» в пути САМА ПО СЕБЕ не отклоняется: /hs/mcp@1c и
// /hs/mcp-1c@v2 это рабочие имена служб 1С, и учётных данных в них нет.
//
// Функция никогда не возвращает частично очищенный адрес: либо Base не
// содержит учётных данных, либо возвращается ошибка и нулевой результат.
func SplitURLCredentials(raw string) (BaseURLSplit, error) {
	// Шаг 1. Строка без «@» не может нести userinfo: «@» это единственный
	// разделитель userinfo в RFC 3986, а «%40» разделителем не является. «?» и
	// «#» исключены здесь только для того, чтобы их увидел шаг 4. Возврат
	// исходной строки байт в байт — это то, что сохраняет работоспособность
	// уже настроенных адресов и внутренних схем.
	if !strings.ContainsAny(raw, "@?#") {
		return BaseURLSplit{Base: raw, Display: displayBaseOf(parseQuiet(raw))}, nil
	}

	parsed, err := url.Parse(raw)
	if err != nil {
		// *url.Error печатает %q сырого адреса, а «invalid port \":pa\" after
		// host» печатает и кусок пароля. Исходную ошибку не возвращаем.
		if strings.ContainsRune(raw, '@') {
			return BaseURLSplit{}, ErrURLCredentialUnstrippable
		}
		return BaseURLSplit{}, ErrBaseURLUnparsable
	}

	// Шаг 2. Opaque значит, что после схемы не было «//», то есть authority
	// нет вовсе и снимать userinfo неоткуда.
	if parsed.Opaque != "" {
		return BaseURLSplit{}, ErrURLCredentialUnstrippable
	}

	// Шаг 3. Защита от того, чего net/url выдать не должен.
	if strings.ContainsRune(parsed.Host, '@') {
		return BaseURLSplit{}, ErrURLCredentialUnstrippable
	}

	// Шаг 4. «@» в пути. По RFC 3986 это законный символ пути, и имена служб
	// 1С его действительно содержат: /hs/mcp@1c и /hs/mcp-1c@v2 это рабочие
	// адреса. Отказывать во всех «@» за пределами authority нельзя, отказывать
	// ни в одной тоже: именно «@» в пути превращает
	// http://user:1234/passZ@host/hs в нечто иное, чем имел в виду
	// администратор.
	//
	// РАЗЛИЧАЕТ ИХ ДВОЕТОЧИЕ. Чтобы «@» была разделителем userinfo, перед ней
	// должна стоять пара «логин:пароль», а пара требует двоеточия. Если
	// двоеточия до «@» нет вовсе, то читать её как разделитель нечем, пароля
	// там нет, и в сохранённом адресе нечему утечь.
	//
	// Двоеточие ищется в ДВУХ местах, потому что усечённый authority бывает
	// обеих форм: у http://user:1234/passZ@host/hs двоеточие попало в Host
	// (net/url прочитал 1234 как порт), у http://us/er:passZZ@host/hs оно
	// осталось в пути.
	//
	// СЛЕДСТВИЕ, КОТОРОЕ НАЗВАНО ВСЛУХ: явный порт неотличим от такого
	// усечения, поэтому http://сервер:8080/hs/mcp-1c@v2 отклоняется. Выход
	// один и тот же для обоих случаев и он проверен испытанием: записать «@»
	// как «%40».
	if rawPath := rawPathOf(parsed); strings.ContainsRune(rawPath, '@') {
		if parsed.User != nil {
			// userinfo уже нашлась, и за ней стоит ещё одна «@». Какую из них
			// имел в виду администратор, неизвестно.
			return BaseURLSplit{}, ErrURLCredentialUnstrippable
		}
		at := strings.IndexRune(rawPath, '@')
		if parsed.Port() != "" || strings.ContainsRune(rawPath[:at], ':') {
			return BaseURLSplit{}, ErrBaseURLAmbiguousAt
		}
	}

	// Шаг 5. «?» или «#». Проверяем сырую строку, а не поля: литеральный «?»
	// в адресе всегда разделитель, потому что validUserinfo его не пропускает
	// (/usr/local/go/src/net/url/url.go:1267-1300), а закодированный «%3F»
	// разделителем не является и сюда не попадёт.
	//
	// Какое из двух сообщений печатать, решает наличие userinfo, а не догадка
	// о содержимом строки запроса: если net/url нашёл userinfo, администратор
	// точно записал в адрес учётные данные, и это срочнее.
	if isDialedScheme(parsed.Scheme) && strings.ContainsAny(raw, "?#") {
		if parsed.User != nil {
			return BaseURLSplit{}, ErrURLCredentialUnstrippable
		}
		return BaseURLSplit{}, ErrBaseURLHasQueryOrFragment
	}

	if parsed.User == nil {
		// «@» была, но не в authority, не в пути и не в строке запроса.
		// Учётных данных нет, адрес отдаём байт в байт.
		return BaseURLSplit{Base: raw, Display: displayBaseOf(parsed)}, nil
	}

	user := parsed.User.Username()
	password, _ := parsed.User.Password()

	stripped := *parsed
	stripped.User = nil
	base := stripped.String()

	// Шаг 6. Обязательство доказать результат, а не предположить его.
	//
	// Раньше здесь стояло «в base не должно быть ни одной «@»». Это неверная
	// формулировка того же требования: url.URL.String() собирает путь через
	// EscapedPath(), а тот для пути с сырой кириллицей ПЕРЕСОБИРАЕТ его из
	// раскодированного Path, и «%40» превращается обратно в «@», потому что в
	// пути «@» экранировать не нужно. Измерено: для
	// http://admin:secret@1c.corp.local/база/%40x/hs результат снятия равен
	// http://1c.corp.local/%D0%B1%D0%B0%D0%B7%D0%B0/@x/hs, и старая проверка
	// отклоняла собственный корректный результат.
	if !strippedKeepsAuthority(base, parsed.Host) {
		return BaseURLSplit{}, ErrURLCredentialUnstrippable
	}

	return BaseURLSplit{
		Base:        base,
		User:        user,
		Password:    password,
		HadUserinfo: true,
		Display:     displayBaseOf(&stripped),
	}, nil
}

// CheckURLCredentialResidue — та же проверка ради одной только ошибки.
//
// У неё НЕТ собственных ветвлений намеренно. Прежняя версия начиналась с
// «if _, _, _, had := SplitURLCredentials(raw); had { return nil }», и этот
// возврат делал проверку структурно недостижимой ровно для той формы, ради
// которой она существовала. Здесь короткого замыкания нет и добавить его
// некуда: вердикт один и тот же объект.
func CheckURLCredentialResidue(raw string) error {
	_, err := SplitURLCredentials(raw)
	return err
}

// DisplayBase возвращает «схема://хост» для адреса, который прошёл проверку,
// и пустую строку для отклонённого. Отдельная функция нужна тем вызывающим,
// у кого нет BaseURLSplit под рукой.
func DisplayBase(raw string) string {
	res, err := SplitURLCredentials(raw)
	if err != nil {
		return ""
	}
	return res.Display
}

// displayBaseOf собирает строку показа ТОЛЬКО из Scheme и Host.
//
// Ни одна другая часть адреса в неё не попадает, поэтому она не может нести
// ни userinfo (net/url держит её в поле User, а не в Host), ни строку
// запроса, ни фрагмент, ни путь. Это структурное свойство, а не проверка.
func displayBaseOf(parsed *url.URL) string {
	if parsed == nil || parsed.Host == "" {
		return ""
	}
	if parsed.Scheme == "" {
		return parsed.Host
	}
	return parsed.Scheme + "://" + parsed.Host
}

// strippedKeepsAuthority разбирает уже очищенный адрес ЗАНОВО и проверяет, что
// снятие userinfo не изменило authority: userinfo больше нет, хост тот же.
//
// ЧЕСТНО О ТОМ, ЧТО ЭТО ТАКОЕ. Это обязательство доказать результат, а НЕ
// фильтр. Ни одна строка набора до него не доходит: к шагу 6 уже известно, что
// userinfo нашлась, что в сыром пути нет «@», что для сетевой схемы нет «?» и
// «#» и что в Host нет «@», и после этого url.URL.String() authority изменить
// нечем. Измерено мутацией: если выключить вызов, набор из 53 строк остаётся
// зелёным. Ровно то же верно и для той проверки, которую эта заменила: если на
// коммите 04611e9 выключить «в base не должно быть ни одной @», набор из 47
// строк тоже остаётся зелёным. То есть это свойство унаследовано, а не
// приобретено, и зелёный набор его НЕ подтверждает.
//
// Поэтому у функции есть собственное испытание с придуманными входами, где она
// обязана вернуть false, и структурное испытание на то, что вызов на месте.
// Иначе получилась бы проверка, которая не может упасть, и её зелёный читался
// бы как доказательство.
func strippedKeepsAuthority(base, wantHost string) bool {
	back, err := url.Parse(base)
	if err != nil {
		return false
	}
	return back.User == nil && back.Host == wantHost
}

// rawPathOf возвращает путь адреса ровно в том виде, в каком его записал
// администратор.
//
// EscapedPath() для этого не годится, и это измерено, а не выведено. Он
// возвращает RawPath только тогда, когда тот проходит validEncoded
// (/usr/local/go/src/net/url/url.go), а сырые байты кириллицы её не проходят:
// validEncoded зовёт shouldEscape для каждого байта, и всё выше 0x7F она
// экранировать требует. Тогда EscapedPath() ПЕРЕСОБИРАЕТ путь из
// раскодированного Path, и «%40» превращается обратно в «@», потому что «@» в
// пути экранировать не нужно.
//
// Что это давало: для http://admin:secret@host/база/%40x/hs EscapedPath()
// отдавал /%D0%B1%D0%B0%D0%B7%D0%B0/@x/hs, а для точно такого же адреса с
// латинским путём отдавал /base/%40x/hs. Одна и та же запись «%40» получала два
// разных ответа, и адрес с кириллическим именем базы отклонялся, а его
// латинский двойник принимался.
//
// setPath (там же) кладёт в RawPath ИСХОДНУЮ строку пути и оставляет RawPath
// пустым ровно тогда, когда исходная строка совпадает с escape(Path). Поэтому
// «RawPath, если он есть, иначе EscapedPath()» это и есть то, что было
// написано, без пересборки.
func rawPathOf(u *url.URL) string {
	if u.RawPath != "" {
		return u.RawPath
	}
	return u.EscapedPath()
}

// parseQuiet разбирает адрес и возвращает nil вместо ошибки. Используется
// только для строки показа: адрес, который net/url не разбирает, показывать
// нечем, и это не повод отказывать в адресе без «@».
func parseQuiet(raw string) *url.URL {
	parsed, err := url.Parse(raw)
	if err != nil {
		return nil
	}
	return parsed
}

// isDialedScheme сообщает, что по этому адресу onec.Client действительно
// пойдёт в сеть как по HTTP. Внутренние схемы (proxy://, poll://) перехватывает
// свой транспорт, и правило про «?» и «#» к ним не относится.
func isDialedScheme(scheme string) bool {
	switch strings.ToLower(scheme) {
	case "http", "https", "":
		return true
	}
	return false
}

// ScrubbedURLError убирает учётные данные из адреса, который несёт *url.Error.
//
// Нужна даже после разделения на границе: http.Client.Do строит свой
// *url.Error из URL запроса и маскирует только ПАРОЛЬ
// (/usr/local/go/src/net/http/client.go:1047), логин печатается целиком.
// А *url.Error от url.Parse не маскирует вообще ничего: он печатает %q сырого
// адреса (/usr/local/go/src/net/url/url.go:40).
//
// Если адрес очистить нельзя, из ошибки убирается адрес целиком: операция и
// причина остаются, адреса нет. Лучше потерять диагностику, чем напечатать
// пароль.
func ScrubbedURLError(err error) error {
	var ue *url.Error
	if !errors.As(err, &ue) {
		return err
	}
	res, splitErr := SplitURLCredentials(ue.URL)
	if splitErr != nil {
		return fmt.Errorf("%s: %w", ue.Op, ue.Err)
	}
	if !res.HadUserinfo {
		return err
	}
	return &url.Error{Op: ue.Op, URL: res.Base, Err: ue.Err}
}
